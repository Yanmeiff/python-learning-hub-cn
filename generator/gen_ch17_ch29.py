#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate and check CH17–CH29 based on the original PyQuest question schema.

Authoring recipe files are in generator/recipes/*.json. Each chapter has
five distinct tasks in each of four difficulty tiers, and each task has six
input variants: 5 × 6 × 4 = 120 questions per chapter.

The official PyQuest CH01–CH15 bank, CH16, and learner progress are untouched.
All expected outputs and assertions are generated by EXECUTING actual Python
reference solutions using generator/framework.py.
"""
import argparse
import json
import os
import sys
from pathlib import Path

sys.path.insert(0, os.path.dirname(__file__))
from framework import run

ROOT = Path(__file__).resolve().parent.parent
RECIPE_DIR = ROOT / "generator" / "recipes"
RECIPE_FILES = ("chapters17_20.json", "chapters21_24.json", "chapters25_29.json")
FILES = {"E": "easy_30.json", "M": "medium_30.json",
         "H": "hard_30.json", "X": "expert_30.json"}
LEVELS = {"E": ("超简单", "⭐"), "M": ("简单", "⭐⭐"),
          "H": ("中等", "⭐⭐⭐"), "X": ("较难", "⭐⭐⭐⭐")}
WORDS = ("alpha", "beta", "gamma", "delta", "omega", "python",
         "coding", "vector", "lambda")
REQUIRED = {"id", "topic", "difficulty", "stars", "description",
            "code_template", "expected_output", "hints", "test_cases", "solution"}
NEW_CATEGORIES = (
    {"id": "object-oriented", "label": "类、继承与协议",
     "chapters": ["CH17", "CH18", "CH20", "CH24"]},
    {"id": "modules-files", "label": "模块与文件处理",
     "chapters": ["CH19", "CH25"]},
    {"id": "decorators-exceptions", "label": "装饰器、异常与正则",
     "chapters": ["CH21", "CH22", "CH23"]},
    {"id": "typing-quality", "label": "类型、测试与工程",
     "chapters": ["CH26", "CH28", "CH29"]},
    {"id": "async-concurrency", "label": "异步与并发",
     "chapters": ["CH27"]},
)


def load_recipes():
    out = {}
    for filename in RECIPE_FILES:
        block = json.loads((RECIPE_DIR / filename).read_text(encoding="utf-8"))
        for key, chapter in block.items():
            if key in out:
                raise AssertionError("Duplicate chapter recipe " + key)
            out[key] = chapter
    assert set(out) == {"CH{:02d}".format(x) for x in range(17, 30)}
    return out


def build_question(ch_id, title, level, index, variant, recipe):
    ch_number = int(ch_id[2:])
    n = variant
    a = 13 + 3 * n
    b = 3 + n
    nums = [a, b, a + 1, b + 2, a - 1]
    word = WORDS[(ch_number + index + variant) % len(WORDS)]
    number = index * 6 + variant
    tag = ch_number * 1000 + ("EMHX".index(level) + 1) * 100 + number
    prefix = (
        "n = {!r}\na = {!r}\nb = {!r}\nnums = {!r}\nword = {!r}\n"
        "case_tag = {!r}".format(n, a, b, nums, word, tag)
    )
    body = recipe["body"]
    answer = recipe["answer"]
    assert body.count("___") == 1, (ch_id, level, number, "placeholder")
    assert answer and "___" not in answer, (ch_id, level, number, "answer")
    code_template = prefix + "\n" + body + "\nprint(case_tag, result)"
    solution = prefix + "\n" + body.replace("___", answer) + "\nprint(case_tag, result)"
    output = run(solution)
    assert output.startswith(str(tag) + " "), (ch_id, level, number, output)
    assertion = "assert captured_output == " + repr(output)
    exec(assertion, {"captured_output": output})
    diff, stars = LEVELS[level]
    question = {
        "id": "{}-{}-{:03d}".format(ch_id, level, number),
        "topic": title,
        "difficulty": diff,
        "stars": stars,
        "description": recipe["title"] + "：" +
          "请根据代码注释及变量，补全 ___ 处的关键表达式或语句，使程序输出正确的计算结果。"
          if "description" not in recipe else recipe["description"],
        "code_template": code_template,
        "expected_output": output,
        "hints": recipe["hint"],
        "test_cases": [assertion],
        "solution": solution,
    }
    assert set(question) == REQUIRED
    return question


def generate():
    recipes = load_recipes()
    chapters = {}
    for ch_id, data in sorted(recipes.items()):
        title = data["title"]
        all_outputs, all_ids = set(), set()
        files = {}
        assert set(data["tiers"]) == set(FILES), ch_id
        for level, filename in FILES.items():
            tier = data["tiers"][level]
            assert len(tier) == 5, (ch_id, level, "five distinct tasks")
            questions = []
            for index, recipe in enumerate(tier):
                for variant in range(1, 7):
                    item = build_question(ch_id, title, level, index, variant, recipe)
                    assert item["id"] not in all_ids
                    assert item["expected_output"] not in all_outputs
                    all_ids.add(item["id"])
                    all_outputs.add(item["expected_output"])
                    questions.append(item)
            assert len(questions) == 30
            files[filename] = {"chapter": ch_id, "title": title,
                               "difficulty": LEVELS[level][0], "questions": questions}
        assert len(all_ids) == 120, ch_id
        chapters[ch_id] = {"name": data["dir"], "title": title, "files": files}
    return chapters


def json_text(payload):
    return json.dumps(payload, ensure_ascii=False, indent=2) + "\n"


def update_index(index, chapters):
    assert len([c for c in index["chapters"] if c["id"] <= "CH16"]) == 16
    index["chapters"] = [c for c in index["chapters"] if c["id"] < "CH17"]
    for ch_id, data in sorted(chapters.items()):
        index["chapters"].append({
            "id": ch_id,
            "dir": data["name"],
            "title": ch_id + " " + data["title"],
            "count": 120,
            "files": [
                {"diff": suffix, "file": name, "n": 30}
                for suffix, name in (("E","easy_30.json"), ("X","expert_30.json"),
                                     ("H","hard_30.json"), ("M","medium_30.json"))
            ],
        })
    assert len(index["chapters"]) == 29
    assert sum(c["count"] for c in index["chapters"]) == 3460
    return index


def update_topic_map(topic_map):
    ids = {c["id"] for c in NEW_CATEGORIES}
    topic_map["categories"] = [x for x in topic_map["categories"]
                               if x["id"] not in ids]
    topic_map["categories"].extend(NEW_CATEGORIES)
    topic_map["description"] = "PyQuest 29 章题库的知识领域映射；掌握度基于最近一次作答。"
    return topic_map


def write_or_check(path, payload, check):
    content = json_text(payload)
    if check:
        assert path.is_file(), "Missing generated file: " + str(path)
        assert json.loads(path.read_text(encoding="utf-8")) == payload, \
            "Outdated generated file: " + str(path)
    else:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="verify all generated files against freshly run Python solutions")
    parser.add_argument("--write", action="store_true",
                        help="generate all chapter files and site index")
    args = parser.parse_args()
    if args.check == args.write:
        parser.error("Specify exactly one of --check or --write")
    chapters = generate()
    for ch_id, chapter in sorted(chapters.items()):
        for filename, payload in chapter["files"].items():
            for prefix in ("questions", "docs/data/questions"):
                write_or_check(ROOT / prefix / chapter["name"] / filename, payload, args.check)
        print("OK: {} {} (120 questions)".format(ch_id, chapter["title"]))
    index_path = ROOT / "docs/data/index.json"
    index = json.loads(index_path.read_text(encoding="utf-8"))
    write_or_check(index_path, update_index(index, chapters), args.check)
    map_path = ROOT / "docs/data/topic-map.json"
    topic_map = json.loads(map_path.read_text(encoding="utf-8"))
    write_or_check(map_path, update_topic_map(topic_map), args.check)
    print("Advanced bank verified: 13 new chapters, 1560 new questions; 29 chapters / 3460 total.")


if __name__ == "__main__":
    main()
